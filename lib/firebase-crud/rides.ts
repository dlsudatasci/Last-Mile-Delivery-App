export const saveRide = async (rideData: NewRideData) => {
    try {
        const userId = getAuth().currentUser?.uid;
        if (!userId) {
            throw new Error('User not authenticated');
        }
        const ridesCollectionRef = collection(firestore, 'rides');

        const batch = writeBatch(firestore);
        // Save main ride data without points
        const { points, annotations = [], generatedRoutes = [], isGPXUpload, fromWeb, ...rideDataWithoutPoints } = rideData;

        if (!points || points.length === 0) {
            throw new Error('No ride points provided');
        }

        let gpxUpload = false;
        let webSource = false;
        if (isGPXUpload) {
            gpxUpload = true;
        }
        if (fromWeb) {
            webSource = true;
        }

        const rideDocRef = doc(ridesCollectionRef);
        const annotationsCollectionRef = collection(rideDocRef, 'annotations');
        const processedAnnotations = await Promise.all(
            annotations.map(async annotation => {
                if (!annotation) {
                    return;
                }

                const annotationDocRef = doc(annotationsCollectionRef);
                const uploadMedia = async (mediaUri: string) => {
                    if (!mediaUri) {
                        return null;
                    }
                    const mediaRef = storage().ref(`rides/${rideDocRef.id}/annotations/${annotationDocRef.id}`);
                    const task = mediaRef.putFile(mediaUri);

                    task.on('state_changed', snapshot => {
                        console.log('Upload is ' + snapshot.bytesTransferred);
                    });
                    await task;
                    return await mediaRef.getDownloadURL();
                };
                batch.set(annotationDocRef, {
                    ...annotation,
                    mediaType: annotation.mediaType ?? null,
                    mediaUri: annotation.mediaUri ? await uploadMedia(annotation.mediaUri) : null,
                    id: annotationDocRef.id,
                    userId: userId,
                    rideId: rideDocRef.id,
                    createdAt: Date.now(),
                });
            })
        );

        batch.set(rideDocRef, {
            ...rideDataWithoutPoints,
            id: rideDocRef.id,
            userId: userId,
            createdAt: Date.now(),
            isGPXUpload: gpxUpload,
            fromWeb: webSource,
        });

        // Save generated routes to top-level generatedRoutes collection
        const generatedRoutesCollectionRef = collection(firestore, 'generatedRoutes');
        generatedRoutes.forEach(route => {
            const routeDocRef = doc(generatedRoutesCollectionRef, route.routeId);
            batch.set(routeDocRef, {
                ...route,
                rideId: rideDocRef.id,
            });
        });

        // Save points in a single document under map/points
        const mapCollectionRef = collection(rideDocRef, 'map');
        const pointsDocRef = doc(mapCollectionRef, 'points');
        batch.set(pointsDocRef, {
            items: points,
        });

        await batch.commit();

        return rideDocRef.id;
    } catch (error) {
        console.error('Error saving ride:', error);
        throw error;
    }
};

