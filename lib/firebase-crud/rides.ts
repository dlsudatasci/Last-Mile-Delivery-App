export const deleteRide = async (ride: FetchRideData) => {
    try {
        const rideDocRef = doc(firestore, 'rides', ride.id);
        const batch = writeBatch(firestore);
        const annotationsCollectionRef = collection(rideDocRef, 'annotations');
        const annotationsDocRefs = ride.annotations.map(annotation => {
            const mediaRef = storage().ref(`rides/${ride.id}/annotations/${annotation.id}`);
            return {
                docRef: doc(annotationsCollectionRef, annotation.id),
                mediaRef: mediaRef,
            };
        });
        annotationsDocRefs.forEach(docRef => {
            batch.delete(docRef.docRef);
            deleteObject(docRef.mediaRef);
        });
        const pointsDocRef = doc(collection(rideDocRef, 'map'), 'points');
        batch.delete(rideDocRef);
        batch.delete(pointsDocRef);
        await batch.commit();
    } catch (error) {
        console.error('Error deleting ride:', error);
        throw error;
    }
};

